alter table public.payment_transactions
  add constraint payment_transactions_purpose_check
  check (purpose in ('membership_joining', 'membership_recurring', 'backmi_gift', 'huurdit_activation'));

-- Capture first-valid referral attribution at auth-account creation time.
create or replace function public.handle_new_we_rise_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  new_name text;
  configured_trial_days integer := 3;
  new_province text;
  new_city_town text;
  new_country text;
  incoming_referral text;
  referral_owner varchar(120);
  referral_program varchar(20);
begin
  select trial_days into configured_trial_days from public.payment_settings where id = 1;
  configured_trial_days := coalesce(configured_trial_days, 3);
  new_name := nullif(trim(coalesce(new.raw_user_meta_data ->> 'display_name', new.raw_user_meta_data ->> 'full_name', '')), '');
  if new_name is null then new_name := split_part(coalesce(new.email, 'We-Rise Lady'), '@', 1); end if;
  new_province := nullif(trim(coalesce(new.raw_user_meta_data ->> 'province', '')), '');
  new_city_town := nullif(trim(coalesce(new.raw_user_meta_data ->> 'city_town', '')), '');
  new_country := nullif(trim(coalesce(new.raw_user_meta_data ->> 'country', '')), '');
  incoming_referral := regexp_replace(upper(trim(coalesce(new.raw_user_meta_data ->> 'referral_code', ''))), '[^A-Z0-9]', '', 'g');

  if incoming_referral <> '' then
    select rp.member_key, rp.program_type
      into referral_owner, referral_program
    from public.referral_programs rp
    where upper(rp.referral_code) = incoming_referral
      and rp.status = 'active'
      and rp.member_key <> new.id::text
    limit 1;
  end if;

  insert into public.member_profiles (
    member_key, auth_user_id, email, display_name, province, city_town, country, plan, role, membership_status,
    trial_started_at, trial_ends_at, referred_by_member_key, referral_code_used, referral_program_used, referred_at,
    created_at, updated_at, last_seen_at
  ) values (
    new.id::text,
    new.id,
    lower(new.email),
    left(new_name, 80),
    left(new_province, 80),
    left(new_city_town, 100),
    left(new_country, 80),
    'free',
    'member',
    'trialing',
    now(),
    now() + make_interval(days => configured_trial_days),
    referral_owner,
    case when referral_owner is not null then incoming_referral else null end,
    referral_program,
    case when referral_owner is not null then now() else null end,
    now(),
    now(),
    now()
  )
  on conflict (member_key) do update
    set auth_user_id = excluded.auth_user_id,
        email = excluded.email,
        province = coalesce(public.member_profiles.province, excluded.province),
        city_town = coalesce(public.member_profiles.city_town, excluded.city_town),
        country = coalesce(public.member_profiles.country, excluded.country),
        referred_by_member_key = coalesce(public.member_profiles.referred_by_member_key, excluded.referred_by_member_key),
        referral_code_used = coalesce(public.member_profiles.referral_code_used, excluded.referral_code_used),
        referral_program_used = coalesce(public.member_profiles.referral_program_used, excluded.referral_program_used),
        referred_at = coalesce(public.member_profiles.referred_at, excluded.referred_at),
        updated_at = now();
  return new;
end;
$$;

